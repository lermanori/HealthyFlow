/**
 * Point a physical-device build at this Mac's backend.
 *
 * `build:ios:local` bakes in `localhost:3001`, which on a phone is the phone —
 * so it only ever works on the simulator. A device needs the Mac's LAN address,
 * and that address changes with the network, so it is resolved at build time
 * rather than committed.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'

function lanAddress() {
  for (const nic of ['en0', 'en1']) {
    try {
      const address = execFileSync('ipconfig', ['getifaddr', nic], { encoding: 'utf8' }).trim()
      if (address) return address
    } catch {
      // This interface is not the active one. Try the next.
    }
  }
  return null
}

const address = lanAddress()
if (!address) {
  console.error(
    'Could not find this Mac\'s LAN address. Connect to Wi-Fi, or set VITE_API_URL by hand.',
  )
  process.exit(1)
}

const api = `http://${address}:3001/api`
fs.writeFileSync(
  '.env.device-build',
  `# Generated by scripts/build-ios-device-env.mjs — do not commit.\n`
  + `# A phone cannot reach the Mac's localhost, so the LAN address is baked in.\n`
  + `VITE_API_URL=${api}\n`
  + `VITE_CLOUD_SYNC_ENABLED=true\n`,
)

console.log(`iOS device build will call ${api}`)
console.log('The phone and this Mac must be on the same network.')
